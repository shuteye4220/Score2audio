"""Writes digits_gen.go: shapes of the digits 0-9 in common book and music
fonts, which score2audio compares printed metronome numbers against.

usage: python3 tools/digits/gen.py > digits_gen.go   (needs Pillow and the fonts)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

GW, GH = 8, 12  # the grid a digit is measured on (keep in step with digitGrid*)
FONTS = [
    '/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSerif-Italic.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSerif-BoldItalic.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf',
    '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
    '/usr/share/fonts/truetype/freefont/FreeSerif.ttf',
    '/usr/share/fonts/truetype/freefont/FreeSerifBold.ttf',
    '/usr/share/fonts/truetype/freefont/FreeSans.ttf',
    '/usr/share/fonts/truetype/freefont/FreeSansBold.ttf',
    '/usr/share/texmf/fonts/opentype/public/lm/lmroman10-regular.otf',
    '/usr/share/texmf/fonts/opentype/public/lm/lmroman10-bold.otf',
]
skip = set(sys.argv[1:])  # fonts to leave out (for testing on unseen fonts)


def features(img):
    """img: a cropped black-on-white 'L' image of one digit."""
    w, h = img.size
    px = img.load()
    out = []
    for gy in range(GH):
        for gx in range(GW):
            x0, x1 = gx * w / GW, (gx + 1) * w / GW
            y0, y1 = gy * h / GH, (gy + 1) * h / GH
            ink = tot = 0
            for y in range(int(y0), max(int(y0) + 1, int(y1 + 0.999))):
                for x in range(int(x0), max(int(x0) + 1, int(x1 + 0.999))):
                    if x < w and y < h:
                        tot += 1
                        ink += px[x, y] < 128
            out.append(min(15, round(15 * ink / max(1, tot))))
    return out, w / h


print('// Code generated by tools/digits/gen.py; DO NOT EDIT.\n')
print('package main\n')
print('var digitTemplates = []digitTemplate{')
for f in FONTS:
    if any(s in f for s in skip):
        continue
    font = ImageFont.truetype(f, 96)
    for d in '0123456789':
        im = Image.new('L', (160, 160), 255)
        ImageDraw.Draw(im).text((30, 10), d, font=font, fill=0)
        im = im.point(lambda v: 0 if v < 128 else 255)
        box = Image.eval(im, lambda v: 255 - v).getbbox()
        feat, aspect = features(im.crop(box))
        print(f'\t{{{d}, {aspect:.3f}, "{"".join("%x" % v for v in feat)}"}}, // {f.rsplit("/", 1)[1]}')
print('}')
